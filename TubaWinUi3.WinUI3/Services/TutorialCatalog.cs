    /// <summary>获取工具教程；未收录的工具按元信息自动生成一份基础教程。</summary>
    public static ToolTutorial Get(IBuiltinTool tool)
    {
        if (_tutorials.TryGetValue(tool.Id, out var t)) return t;
        return BuildFallback(tool);
    }

    private static ToolTutorial BuildFallback(IBuiltinTool tool)
    {
        var steps = new List<TutorialStep>
        {
            new($"打开「{tool.Name}」", $"在主界面左侧分类导航中找到「{tool.Name}」（分类：{tool.Category}），点击卡片打开；也可用顶部搜索框直接搜索。"),
            new("按界面引导使用", tool.Description),
            new("遇到问题", "如果工具运行异常，可尝试重新打开；涉及网络下载的工具请检查网络连接。")
        };
        return new ToolTutorial(tool.Description, steps, "工具的具体行为以实际界面为准；本教程由工具信息自动生成。");
    }
