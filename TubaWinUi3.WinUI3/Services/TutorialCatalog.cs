namespace TubaWinUi3.Services;

/// <summary>
/// 新手教程内容目录：为所有内置工具提供纯文字步骤教程数据。
/// 注意：本教程不从属于 BuiltinToolRegistry，仅通过主界面标题栏「新手教程」按钮打开。
/// </summary>
public sealed record TutorialStep(string Title, string Body);

public sealed record ToolTutorial(
    string Intro,
    IReadOnlyList<TutorialStep> Steps,
    string Tips)
{
    public ToolTutorial(string intro, (string, string)[] steps, string tips)
        : this(intro, steps.Select(s => new TutorialStep(s.Item1, s.Item2)).ToList(), tips) { }
}

